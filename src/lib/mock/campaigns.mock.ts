/**
 * @deprecated Use getCampaignDetailData() from @/lib/data/get-dashboard-data.
 * Legacy shim for code not yet migrated to the normalized data layer.
 */
export function getCampaignDetail(id: string): CampaignDetail {
  const data = getCampaignDetailData(campaignDetailParams(id));
  if (!data.found) {
    const fallback = MOCK_CAMPAIGNS[0]!;
    return {
      ...fallback,
      adSets: DETAIL_AD_SETS["cmp-01"] ?? [],
      dailyStats: buildLast14DailyStats(fallback.spend, fallback.roas),
      topCreatives: DETAIL_CREATIVES["cmp-01"] ?? [],
      aiTips: DEFAULT_DETAIL_TIPS,
    };
  }

  const c = data.campaign;
  const m = data.metrics;
  return {
    id: c.id,
    name: c.name,
    accountId: c.accountId,
    accountName: data.account.name,
    status: c.status,
    objective: c.objective ?? "conversions",
    dailyBudget: m.dailyBudget ?? 0,
    spend: m.spend,
    revenue: m.revenue,
    budget: c.budget ?? 0,
    roas: m.roas,
    clicks: m.clicks ?? 0,
    impressions: m.impressions ?? 0,
    ctr: m.ctr ?? 0,
    cpc: m.cpc ?? 0,
    conversions: m.conversions ?? 0,
    conversionRate: c.conversionRate ?? 0,
    aiHealthScore: m.aiHealthScore,
    startDate: data.schedule.startDate ?? "",
    endDate: data.schedule.endDate ?? "",
    adSets: data.adSets.map((a) => ({
      id: a.id,
      name: a.name,
      audience: a.audience ?? "",
      budget: a.budget ?? 0,
      spend: a.spend,
      roas: a.roas,
      status: a.status,
    })),
    dailyStats: data.dailyTrend.map((d) => ({
      date: d.date,
      spend: d.spend,
      roas: d.roas,
      clicks: d.clicks ?? 0,
      impressions: d.impressions ?? 0,
      conversions: d.conversions ?? 0,
    })),
    topCreatives: data.creatives.map((cr) => ({
      id: cr.id,
      name: cr.name,
      format: cr.format,
      spend: cr.spend,
      roas: cr.roas,
      ctr: cr.ctr,
      thumbnail: cr.thumbnailColor,
    })),
    aiTips: data.insights.map((i) => ({ title: i.title, description: i.description })),
  };
}
